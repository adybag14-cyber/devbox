import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdtemp,readFile,writeFile,rm,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import net from 'node:net';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {Client} from '@modelcontextprotocol/sdk/client/index.js';
import {StreamableHTTPClientTransport} from '@modelcontextprotocol/sdk/client/streamableHttp.js';
const repo=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const binary=process.env.DEVBOX_CPP_BINARY||path.join(repo,'.cpp-build/windows/cpp-mcp/Release/devbox-mcp.exe');
const binaryHash=createHash('sha256').update(await readFile(binary)).digest('hex');
const root=await mkdtemp(path.join(os.tmpdir(),'devbox-cpp-engine-sdk-'));
const workspace=path.join(root,'workspace'); await mkdir(workspace);
const port=await new Promise((resolve,reject)=>{const socket=net.createServer();socket.once('error',reject);socket.listen(0,'127.0.0.1',()=>{const number=socket.address().port;socket.close(()=>resolve(number));});});
const delay=ms=>new Promise(resolve=>setTimeout(resolve,ms));
const env={...process.env,DEVBOX_PROJECT_ROOT:root,HOST:'127.0.0.1',PORT:String(port),MCP_AUTH_MODE:'none',PUBLIC_BASE_URL:'',DEVBOX_RUNTIME_MODE:'host',ENABLE_HOST_EXEC:'true',DEVBOX_AUTO_START:'false',HOST_WORKSPACE_PATH:workspace,DEVBOX_WORKSPACE_PATH:workspace,HOST_DEFAULT_WORKDIR:workspace,NODE_EXE:process.execPath,HOST_SHELL:process.platform==='win32'?'cmd.exe':'/bin/sh',MCP_JOBS_ROOT:path.join(root,'jobs'),MCP_EXEC_SLOT_ROOT:path.join(root,'slots'),MCP_PERFORMANCE_STATE_PATH:path.join(root,'run','mcp-performance.json'),MAX_COMMAND_OUTPUT_CHARS:'65536',MAX_TEXT_OUTPUT_CHARS:'4000000',MAX_MCP_TRANSFER_CHARS:'4000000',MCP_WAIT_MAX_SECONDS:'85',DEVBOX_MCP_RUNTIME_ENV_AUTHORITATIVE:'0'};
const child=spawn(binary,[],{cwd:repo,env,windowsHide:true,stdio:['ignore','pipe','pipe']});
let output='';for(const stream of [child.stdout,child.stderr])stream.on('data',chunk=>{output=(output+chunk.toString()).slice(-16000);});
const exited=new Promise((resolve,reject)=>{child.once('exit',resolve);child.once('error',reject);});
let client;
try {
  const base=`http://127.0.0.1:${port}`; const deadline=Date.now()+20000;
  for(;;){assert(Date.now()<deadline,`Candidate failed to start: ${output}`);assert.equal(child.exitCode,null,output);
    try {const response=await fetch(base,{signal:AbortSignal.timeout(500)});if(response.ok){const metadata=await response.json();assert.equal(metadata.build.binarySha256,binaryHash,'exact candidate ownership');break;}}catch(error){if(error.code==='ERR_ASSERTION')throw error;}await delay(50);}
  client=new Client({name:'cpp-engine-sdk-smoke',version:'1'}, {capabilities:{}});
  await client.connect(new StreamableHTTPClientTransport(new URL(`${base}/mcp`)));
  const listed=(await client.listTools()).tools;
  assert.equal(listed.length,45,'complete implemented tool family');
  const invoke=async(name,args={})=>{const result=await client.callTool({name,arguments:args});assert.equal(result.isError,false,JSON.stringify(result));return result.structuredContent;};
  const capabilities=await invoke('devbox_capabilities');
  assert.equal(capabilities.data.implementation,'cpp');assert.equal(capabilities.data.build.binarySha256,binaryHash);
  assert.deepEqual(capabilities.data.tools,listed.map(tool=>tool.name).sort());
  const pathName=path.join(workspace,'roundtrip.bin');
  const bytes=Buffer.from([0,255,1,2,13,10,254]);
  await invoke('devbox_write_large_file',{path:pathName,content_base64:bytes.toString('base64')});
  assert.deepEqual(Buffer.from((await invoke('devbox_read_large_file',{path:pathName})).data.content_base64,'base64'),bytes);
  const first=await invoke('devbox_task_put',{task_id:'sdk_task',expected_revision:0,state:{phase:'integration'}});
  assert.equal(first.data.record.revision,1);
  const script=path.join(workspace,'job.mjs');
  await writeFile(script,"import{appendFileSync}from'node:fs';appendFileSync(process.argv[2],'x');console.log('native-cpp-job');\n");
  const arguments_={task_id:'sdk_task',operation_id:'once',program:'node',args:[script,path.join(workspace,'counter')]};
  const firstJob=(await invoke('devbox_job_submit',arguments_)).data;
  const replay=(await invoke('devbox_job_submit',arguments_)).data;
  assert.equal(replay.id,firstJob.id);assert.equal(replay.replayed,true);
  const terminal=(await invoke('devbox_job_status',{job_id:firstJob.id,wait_seconds:10})).data;
  assert.equal(terminal.status,'succeeded',JSON.stringify(terminal));assert.equal(await readFile(path.join(workspace,'counter'),'utf8'),'x');
  assert((await invoke('devbox_job_logs',{job_id:firstJob.id})).data.stdout.includes('native-cpp-job'));
  const abort=new AbortController();const pending=client.callTool({name:'devbox_wait',arguments:{seconds:20}},undefined,{signal:abort.signal});
  const cancelled=assert.rejects(pending);await delay(100);abort.abort(new Error('SDK cancellation'));await cancelled;
  await delay(150);
  const waits=Array.from({length:32},()=>invoke('devbox_wait',{seconds:0.4}));
  const started=performance.now();assert.equal(await(await fetch(`${base}/healthz`)).text(),'ok');const healthMs=performance.now()-started;
  assert(healthMs<1000,`Health stalled ${healthMs}ms`);await Promise.all(waits);
  const status=(await invoke('devbox_status')).data;
  assert.equal(status.performance.process.pid,child.pid,'live serving PID');assert.equal(status.executionStore.ok,true);
  assert.equal(status.activeRequests,0,'cancelled/waited requests released');
  assert.equal((await fetch(`${base}/readyz`)).status,listed.length===45?200:503);
  await client.close();client=undefined;
  await delay(100);
  const usage=await readFile(path.join(root,'run','tool-usage.jsonl'),'utf8');assert(usage.includes('tool_finish'));
  console.log(JSON.stringify({ok:true,toolCount:listed.length,binarySha256:binaryHash,servingPid:child.pid,sdk:'1.30.0',nativeJob:true,durableRetry:true,byteRoundtrip:true,concurrentPassiveWaits:32,cancellation:true,healthMs},null,2));
} finally {
  await client?.close().catch(()=>{});
  if(child.exitCode===null&&child.signalCode===null){child.kill();await Promise.race([exited,delay(10000)]);}
  assert(child.exitCode!==null||child.signalCode!==null,'owned candidate stopped');
  await rm(root,{recursive:true,force:true,maxRetries:20,retryDelay:200});
}
