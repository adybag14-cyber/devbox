import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
const base = new URL('../', import.meta.url);
export const registry = JSON.parse(await readFile(new URL('contract/tool-registry.json', base), 'utf8'));
const frozen = JSON.parse(await readFile(new URL('contract/reference-tools.json', base), 'utf8'));
const names = new Set(registry.tools.map(t => t.name));
assert.equal(names.size, registry.tools.length, 'unique tool identities');
for (const tool of registry.tools) {
  assert.match(tool.name, /^[a-z][a-z_]+$/);
  assert.match(tool.scope, /^mcp:(admin|devbox:(read|exec)|host:(read|exec))$/);
  assert(tool.alias_of === null || (tool.alias_of !== tool.name && names.has(tool.alias_of)), 'valid alias target');
  assert.equal(tool.telemetry.payloads, false, 'payloads are never operational telemetry');
  for (const schema of Object.values(tool.schemas)) {
    assert.equal(schema.name, tool.name);
    for (const field of tool.telemetry.safe_fields) assert(field in schema.inputSchema.properties);
  }
}
for (const [profile, schemas] of Object.entries(frozen.profiles)) {
  for (const schema of schemas) {
    assert.deepEqual(registry.tools.find(t => t.name === schema.name)?.schemas[profile], schema,
      `Frozen ${profile}/${schema.name} remains unchanged`);
  }
}
const outputs = new Map();
for (const family of ['computer', 'research'])
  outputs.set(`contract/${family}-tools.json`, JSON.stringify(registry.tools.filter(t => t.family === family).map(t => t.schemas.all), null, 2) + '\n');
const status = JSON.parse(await readFile(new URL('port-status.json', base), 'utf8'));
status.target_tool_count = registry.tools.length;
status.contract_registry = 'contract/tool-registry.json';
outputs.set('port-status.json', JSON.stringify(status, null, 2) + '\n');
outputs.set('../docs/TOOL_MANIFEST.md', '# Devbox tool manifest\n\nGenerated by `node cpp-mcp/scripts/sync-registry.mjs --write` from the canonical C++ registry. Do not edit generated files.\n\n' +
  `Contract version: ${registry.contract_version}. Declared tool count: ${registry.tools.length}. Read-only hints do not provide an OS sandbox.\n\n` +
  '| Tool | Scope | Alias of | Broker | Platforms |\n|---|---|---|---|---|\n' +
  registry.tools.map(t => `| ${t.name} | ${t.scope} | ${t.alias_of ?? ''} | ${t.broker} | ${t.platforms.join(', ')} |`).join('\n') + '\n');
for (const [file, value] of outputs) {
  if (process.argv.includes('--write')) await writeFile(new URL(file, base), value);
  else assert.equal((await readFile(new URL(file, base), 'utf8')).replaceAll('\r\n', '\n'), value, `${file} must be regenerated`);
}
console.log(`Registry verified: ${registry.tools.length} tools, both frozen profiles, permissions, aliases and generated documentation.`);
