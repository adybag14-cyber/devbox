// Development-only extraction of the existing external Docker/Python integration.
// Neither generation nor Rust is required by a compiled C++ executable.
import {execFileSync} from 'node:child_process';
import {writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const baseline = 'cd8803c81ad3a14ec3b3fa2afa0d08256975b1e9';
const source = execFileSync('git', ['show', `${baseline}:rust-mcp/src/docker_files.rs`], {cwd: root, encoding: 'utf8', windowsHide: true});
let header = '#pragma once\n#include <string_view>\n// Generated by export-container-helpers.mjs from the frozen Docker integration.\nnamespace devbox::container_helpers {\n';
for (const name of ['LIST_PYTHON', 'READ_TEXT_PYTHON', 'WRITE_TEXT_PYTHON', 'LARGE_READ_PYTHON', 'LARGE_WRITE_PYTHON']) {
  const start = `const ${name}: &str = r#"`;
  const offset = source.indexOf(start);
  assert(offset >= 0, name);
  const end = source.indexOf('"#;', offset + start.length);
  assert(end > offset, name);
  const script = source.slice(offset + start.length, end).replaceAll('\r\n', '\n');
  assert(!script.includes(')CPP_PY"'));
  header += `inline constexpr std::string_view ${name.toLowerCase()} = R"CPP_PY(${script})CPP_PY";\n`;
}
header += '} // namespace devbox::container_helpers\n';
await writeFile(path.join(root, 'cpp-mcp/include/devbox/container_helpers.hpp'), header);
